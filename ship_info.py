REFERENCE = [
    dict(zip(['name'] + [key for key, _, _ in SHIP_FIELDS], row))
    for row in _REFERENCE_ROWS
]


def name_key(name):
    """Ключ для сопоставления названий: 'Путейский-5 (МС)' -> 'путейский5'."""
    text_ = re.sub(r'\(.*?\)', '', str(name or '').lower().replace('ё', 'е'))
    return re.sub(r'[^0-9a-zа-я]', '', text_)


def find_reference(ship_name):
    """Ищет судно в справочнике по названию (без учёта регистра, пробелов, дефисов и скобок)."""
    key = name_key(ship_name)
    if not key:
        return None
    return next((r for r in REFERENCE if name_key(r['name']) == key), None)


def get_ship_info(ship):
    """Список {label, value} для карточки судна."""
    info = [{'label': 'Судно', 'value': ship.name}]
    for key, label, _ in SHIP_FIELDS:
        value = getattr(ship, key) or ''
        if key == 'core':
            value = CORE_CHOICES.get(value, value)
        info.append({'label': label, 'value': value or '-'})
    return info


def has_ship_info(ship):
    return any(getattr(ship, key) for key, _, _ in SHIP_FIELDS)


def ensure_ship_columns(db):
    """Добавляет новые столбцы характеристик в уже существующую таблицу ships (SQLite)."""
    existing = {c['name'] for c in inspect(db.engine).get_columns('ships')}
    missing = [key for key, _, _ in SHIP_FIELDS if key not in existing]
    if not missing:
        return
    with db.engine.begin() as conn:
        for key in missing:
            length = db.Model.metadata.tables['ships'].c[key].type.length
            conn.execute(text(f'ALTER TABLE ships ADD COLUMN {key} VARCHAR({length})'))
